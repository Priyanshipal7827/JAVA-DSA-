package JAVA.Basic.escapeCharactor;
public class Program1 {
    public static void main(String[] args) {
        /*
         * learn escape charactors
         * 1)"
         * 2)'
         * 3)\t
         * 4)\n
         * 5)\\
         */
        System.out.println("\"mohan\" and \"sohan\"");
        System.out.println('\'');
        System.out.println("today is \tmonday.");
        System.out.println("tommarrow is \ntuesday");
        System.out.println("mohan and \\sohan\\ are here");

    }
}
